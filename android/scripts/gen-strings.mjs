// Generates app/src/main/res/values*/strings.xml from i18n/app-strings.json (English) and
// i18n/app-strings.<lang>.json (translations; a missing key falls back to English at run time).
// Usage: node android/scripts/gen-strings.mjs [--check]
// --check writes nothing and exits 1 if a committed file is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const res = path.join(root, "app/src/main/res");
const read = (name) => JSON.parse(fs.readFileSync(path.join(root, "i18n", name), "utf8")).strings;
const english = read("app-strings.json");

/** The languages of the desktop app, by their Android resource qualifier. */
const LANGUAGES = {
  es: "es", fr: "fr", "pt-BR": "pt-rBR", ru: "ru", id: "in",
  "zh-Hans": "b+zh+Hans", hi: "hi", ar: "ar", bn: "bn",
};

const BS = String.fromCharCode(92);
const esc = (s) =>
  s.split(BS).join(BS + BS)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/'/g, BS + "'").replace(/"/g, BS + '"')
    .replace(/^([@?])/, BS + "$1");

const placeholders = (s) => (s.match(/%\d\$[sd]|%%/g) ?? []).sort().join(" ");

const xmlOf = (strings) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/scripts/gen-strings.mjs. Do not edit. -->\n<resources>\n` +
  Object.entries(strings).map(([k, v]) => `    <string name="${k}">${esc(v)}</string>`).join("\n") + `\n</resources>\n`;

const targets = [[path.join(res, "values/strings.xml"), english]];
for (const [lang, qualifier] of Object.entries(LANGUAGES)) {
  const file = `app-strings.${lang}.json`;
  if (!fs.existsSync(path.join(root, "i18n", file))) continue;
  const translated = read(file);
  const kept = {};
  for (const [k, v] of Object.entries(translated)) {
    if (!(k in english)) { console.error(`${file}: unknown key ${k}`); process.exit(2); }
    if (placeholders(v) !== placeholders(english[k])) { console.error(`${file}: placeholders differ in ${k}`); process.exit(2); }
    kept[k] = v;
  }
  targets.push([path.join(res, `values-${qualifier}/strings.xml`), kept]);
}

// Placeholders must be positional printf arguments (%1$s), not {name}.
if (targets.some(([, strings]) => Object.values(strings).some((v) => /\{\w+\}/.test(v)))) {
  console.error("Placeholders are not supported; use %1$s in app-strings.json.");
  process.exit(2);
}

if (process.argv.includes("--check")) {
  // Windows checkouts may turn LF into CRLF; the content is what matters.
  let stale = false;
  for (const [target, strings] of targets) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== xmlOf(strings)) {
      console.error(`stale: ${path.relative(root, target)}`);
      stale = true;
    }
  }
  process.exit(stale ? 1 : 0);
}
for (const [target, strings] of targets) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, xmlOf(strings));
}
console.log(`${Object.keys(english).length} strings, ${targets.length} languages`);
